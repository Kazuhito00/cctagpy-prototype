class CCTagMarkersBank:
    """Mirrors ``CCTagMarkersBank``: either the built-in table for
    ``n_crowns`` in ``{3, 4}``, or a bank parsed from a text file.
    """

    def __init__(self, n_crowns: int | None = None, file: str | None = None) -> None:
        self._markers: list[list[float]]
        if file is not None:
            self._markers = self._read(file)
        elif n_crowns == 3:
            self._markers = [list(row) for row in ID_THREE_CROWNS]
        elif n_crowns == 4:
            self._markers = [list(row) for row in ID_FOUR_CROWNS]
        else:
            self._markers = []

    @staticmethod
    def _read(file: str) -> list[list[float]]:
        """Parse a plain-text bank file: one marker per line, whitespace
        separated tokens, each either a plain float or an ``n/d`` fraction.
        """
        markers: list[list[float]] = []
        with open(file, encoding="utf-8") as f:
            for line in f:
                tokens = line.split()
                if not tokens:
                    continue
                row: list[float] = []
                ok = True
                for tok in tokens:
                    if "/" in tok:
                        num, _, den = tok.partition("/")
                        try:
                            row.append(float(num) / float(den))
                        except (ValueError, ZeroDivisionError):
                            ok = False
                            break
                    else:
                        try:
                            row.append(float(tok))
                        except ValueError:
                            ok = False
                            break
                if ok and row:
                    markers.append(row)
        return markers

    def get_markers(self) -> list[list[float]]:
        return self._markers
